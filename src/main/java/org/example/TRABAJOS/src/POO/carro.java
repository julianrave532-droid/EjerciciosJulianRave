package POO;

public class carro {

    public String color;
    public int modelo;
    public int llantas;
    public int puestos;
    public String motor;
    public int velocidadfinal;
    public String placa;
    public String transmision;
    public String pais;

    public carro(String color, int modelo, int llantas, int puestos, String motor, int velocidadfinal, String placa, String transmision, String pais) {
        this.color = color;
        this.modelo = modelo;
        this.llantas = llantas;
        this.puestos = puestos;
        this.motor = motor;
        this.velocidadfinal = velocidadfinal;
        this.placa = placa;
        this.transmision = transmision;
        this.pais = pais;
    }
}
